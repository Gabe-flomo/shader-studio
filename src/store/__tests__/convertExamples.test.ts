/**
 * The Convert examples are the converter's own output for two of the Convert
 * page's shaders (Soft circle, Warm tunnel), stored so the example chunk
 * doesn't carry the GLSL parser. This converts the shaders again and fails if
 * the stored graphs have drifted. To refresh them after a converter change:
 *
 *   UPDATE_CONVERT_EXAMPLES=1 npx vitest run convertExamples
 */
import { describe, expect, it } from 'vitest';
import { glslToGraph } from '../../glslToGraph';
import { optimizeGraph } from '../../optimize/optimizeGraph';
import { CONVERT_EXAMPLES } from '../../glslToGraph/examples';
import { estimateNodeHeight, layoutByRank } from '../graphLayout';
import type { GraphNode } from '../../types/nodeGraph';
import { SOFT_CIRCLE_AS_WRITTEN, SOFT_CIRCLE_OPTIMISED, WARM_TUNNEL_AS_WRITTEN, WARM_TUNNEL_OPTIMISED } from '../convertExampleNodes';

const plain = <T,>(v: T): T => JSON.parse(JSON.stringify(v)) as T;

/** As the page runs it: converted, then optimised, the folded blocks spaced again (a block sits where its last member was). */
function convert(code: string) {
  const raw = glslToGraph(code);
  const folded = optimizeGraph(raw.nodes, { minChain: 3, keepSliders: true }).nodes;
  const at = layoutByRank(folded, { heightOf: estimateNodeHeight, order: (a, b) => a.position.y - b.position.y });
  return { raw, opt: folded.map((n): GraphNode => { const p = at.get(n.id); return p ? { ...n, position: p } : n; }) };
}

describe('Convert examples', () => {
  const circle = convert(CONVERT_EXAMPLES.circle.code);
  const tunnel = convert(CONVERT_EXAMPLES.tunnel.code);

  it('are what the Convert page makes of the Soft circle and the Warm tunnel, as written and optimised', async () => {
    if ((import.meta.env as Record<string, unknown>).UPDATE_CONVERT_EXAMPLES) {
      // Node's fs, named at run time: the app's types don't include Node.
      const fs = (await import(/* @vite-ignore */ `node:${'fs'}`)) as { writeFileSync: (f: URL, s: string) => void };
      fs.writeFileSync(new URL('../convertExampleNodes.ts', import.meta.url), `// Generated by src/store/__tests__/convertExamples.test.ts from the Convert page's Soft circle and Warm tunnel
// (glslToGraph, then optimizeGraph as the page runs it). Don't edit by hand:
//   UPDATE_CONVERT_EXAMPLES=1 npx vitest run convertExamples
import type { GraphNode } from '../types/nodeGraph';

export const SOFT_CIRCLE_AS_WRITTEN: GraphNode[] = ${JSON.stringify(plain(circle.raw.nodes), null, 2)};

export const SOFT_CIRCLE_OPTIMISED: GraphNode[] = ${JSON.stringify(plain(circle.opt), null, 2)};

export const WARM_TUNNEL_AS_WRITTEN: GraphNode[] = ${JSON.stringify(plain(tunnel.raw.nodes), null, 2)};

export const WARM_TUNNEL_OPTIMISED: GraphNode[] = ${JSON.stringify(plain(tunnel.opt), null, 2)};
`);
      return;
    }
    for (const [name, c, written, optimised] of [
      ['Soft circle', circle, SOFT_CIRCLE_AS_WRITTEN, SOFT_CIRCLE_OPTIMISED],
      ['Warm tunnel', tunnel, WARM_TUNNEL_AS_WRITTEN, WARM_TUNNEL_OPTIMISED],
    ] as const) {
      expect(c.raw.report.unsupported, name).toEqual([]);
      expect(written, `${name}: the converter changed: refresh the stored graph (see the top of this file)`).toEqual(plain(c.raw.nodes));
      expect(optimised, `${name}: the optimiser changed: refresh the stored graph (see the top of this file)`).toEqual(plain(c.opt));
      expect(optimised.length, name).toBeLessThan(written.length);
    }
  });
});
